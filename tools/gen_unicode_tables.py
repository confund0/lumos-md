#!/usr/bin/env python3
"""Generates src/md/unicode_tables.inc.

Inputs:
- CaseFolding.txt (Unicode Character Database), given by path. The parser
  uses status C and F (full case folding) for link label matching.
- General categories from Python's unicodedata module (its Unicode version
  is written into the output): P* and S* (punctuation for the flanking
  rules), P* alone (host characters of GFM extended autolinks) and Zs
  (whitespace).

Usage:
  gen_unicode_tables.py CaseFolding.txt OUT.inc
  gen_unicode_tables.py --check CaseFolding.txt COMMITTED.inc
With --check the script compares its output with the committed file. It
exits with 77 (skip) if Python's Unicode version differs from the version
in the committed file.

Python 3 standard library only.
"""

import hashlib
import re
import sys
import unicodedata

MAX_CP = 0x10FFFF


def ranges_of(pred):
    out = []
    start = None
    for cp in range(MAX_CP + 2):
        inside = cp <= MAX_CP and pred(cp)
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def is_surrogate(cp):
    return 0xD800 <= cp <= 0xDFFF


def category(cp):
    if is_surrogate(cp):
        return "Cs"
    return unicodedata.category(chr(cp))


def read_case_folding(path):
    data = open(path, "rb").read()
    text = data.decode("utf-8")
    version = None
    m = re.search(r"CaseFolding-(\d+\.\d+\.\d+)\.txt", text)
    if m:
        version = m.group(1)
    entries = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        fields = [f.strip() for f in line.split(";")]
        cp = int(fields[0], 16)
        status = fields[1]
        if status not in ("C", "F"):
            continue
        mapping = [int(x, 16) for x in fields[2].split()]
        if len(mapping) > 3:
            raise SystemExit("case folding with more than 3 code points: %X" % cp)
        entries.append((cp, mapping))
    entries.sort()
    return entries, version, hashlib.sha256(data).hexdigest()


def generate(case_path):
    folds, fold_version, fold_sha = read_case_folding(case_path)
    punct = ranges_of(lambda cp: category(cp)[0] in "PS")
    punct_p = ranges_of(lambda cp: cp >= 0x80 and category(cp)[0] == "P")
    space = ranges_of(lambda cp: category(cp) == "Zs")
    out = []
    w = out.append
    w("// Generated by tools/gen_unicode_tables.py. Do not edit.")
    w("//")
    w("// Sources:")
    w("// - CaseFolding-%s.txt, Unicode Character Database," % fold_version)
    w("//   SHA-256 %s" % fold_sha)
    w("// - General categories P*, S* and Zs from Python %d.%d unicodedata," % sys.version_info[:2])
    w("//   Unicode %s" % unicodedata.unidata_version)
    w("//")
    w("// Unicode License v3. Copyright (c) 1991-2025 Unicode, Inc.")
    w("// Permission is hereby granted, free of charge, to any person obtaining a")
    w("// copy of data files and any associated documentation (the \"Data Files\")")
    w("// or software and any associated documentation (the \"Software\") to deal")
    w("// in the Data Files or Software without restriction, including without")
    w("// limitation the rights to use, copy, modify, merge, publish, distribute,")
    w("// and/or sell copies of the Data Files or Software, and to permit persons")
    w("// to whom the Data Files or Software are furnished to do so, provided that")
    w("// either (a) this copyright and permission notice appear with all copies")
    w("// of the Data Files or Software, or (b) this copyright and permission")
    w("// notice appear in associated Documentation.")
    w("// THE DATA FILES AND SOFTWARE ARE PROVIDED \"AS IS\", WITHOUT WARRANTY OF ANY")
    w("// KIND, EXPRESS OR IMPLIED. Full text:")
    w("// https://www.unicode.org/license.txt")
    w("")
    w("// Unicode version of the general categories.")
    w("#define LUMOS_UNICODE_CATEGORY_VERSION \"%s\"" % unicodedata.unidata_version)
    w("// Unicode version of the case folding table.")
    w("#define LUMOS_UNICODE_CASE_FOLD_VERSION \"%s\"" % fold_version)
    w("")
    w("// Code point ranges [first, last] of general category P* or S*.")
    w("inline constexpr CodeRange punctuation_ranges[] = {")
    for a, b in punct:
        w("    {0x%04X, 0x%04X}," % (a, b))
    w("};")
    w("")
    w("// Code point ranges [first, last] of general category P* from U+0080 on.")
    w("inline constexpr CodeRange punctuation_p_ranges[] = {")
    for a, b in punct_p:
        w("    {0x%04X, 0x%04X}," % (a, b))
    w("};")
    w("")
    w("// Code point ranges [first, last] of general category Zs.")
    w("inline constexpr CodeRange space_ranges[] = {")
    for a, b in space:
        w("    {0x%04X, 0x%04X}," % (a, b))
    w("};")
    w("")
    w("// Full case folding (status C and F), sorted by code point.")
    w("inline constexpr CaseFold case_folds[] = {")
    for cp, m in folds:
        m = m + [0] * (3 - len(m))
        w("    {0x%04X, {0x%04X, 0x%04X, 0x%04X}}," % (cp, m[0], m[1], m[2]))
    w("};")
    return "\n".join(out) + "\n"


def main(argv):
    check = False
    if argv and argv[0] == "--check":
        check = True
        argv = argv[1:]
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    text = generate(argv[0])
    if check:
        committed = open(argv[1], encoding="utf-8").read()
        m = re.search(r'LUMOS_UNICODE_CATEGORY_VERSION "([^"]+)"', committed)
        if not m or m.group(1) != unicodedata.unidata_version:
            print("skip: Python has Unicode %s, the committed file another version" % unicodedata.unidata_version)
            return 77
        # The Python version line may differ; compare the rest.
        strip = lambda s: re.sub(r"from Python \d+\.\d+ unicodedata", "", s)
        if strip(text) != strip(committed):
            print("generated table differs from %s" % argv[1], file=sys.stderr)
            return 1
        print("ok")
        return 0
    with open(argv[1], "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
