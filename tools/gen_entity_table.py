#!/usr/bin/env python3
"""Generates src/md/entity_table.inc.

Input: Python's html.entities.html5, the WHATWG list of HTML5 named
character references (https://html.spec.whatwg.org/entities.json). Only
names with a final ';' are kept: CommonMark does not accept "&copy"
without ';'.

Usage:
  gen_entity_table.py OUT.inc
  gen_entity_table.py --check COMMITTED.inc

Python 3 standard library only.
"""

import html.entities
import re
import sys


def generate():
    names = sorted(
        (k[:-1], v) for k, v in html.entities.html5.items() if k.endswith(";")
    )
    names.sort(key=lambda kv: kv[0].encode("ascii"))
    out = []
    w = out.append
    w("// Generated by tools/gen_entity_table.py. Do not edit.")
    w("//")
    w("// Source: Python %d.%d html.entities.html5, the WHATWG list of HTML5" % sys.version_info[:2])
    w("// named character references (https://html.spec.whatwg.org/entities.json).")
    w("// %d names with a final ';'." % len(names))
    w("//")
    w("// License: CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/).")
    w("// Copyright (c) WHATWG (Apple, Google, Mozilla, Microsoft).")
    w("")
    w("// Sorted by name (byte order), without '&' and ';'.")
    w("inline constexpr EntityEntry entity_table[] = {")
    for name, value in names:
        cps = [ord(c) for c in value]
        if len(cps) > 2:
            raise SystemExit("entity with more than 2 code points: " + name)
        cps += [0] * (2 - len(cps))
        w('    {"%s", 0x%04X, 0x%04X},' % (name, cps[0], cps[1]))
    w("};")
    return "\n".join(out) + "\n"


def main(argv):
    check = False
    if argv and argv[0] == "--check":
        check = True
        argv = argv[1:]
    if len(argv) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    text = generate()
    if check:
        committed = open(argv[0], encoding="utf-8").read()
        strip = lambda s: re.sub(r"Python \d+\.\d+ html", "", s)
        if strip(text) != strip(committed):
            print("generated table differs from %s" % argv[0], file=sys.stderr)
            return 1
        print("ok")
        return 0
    with open(argv[0], "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
